def _iter_provider_entries(
    mail_config: dict,
    *,
    provider_type: str | None = None,
) -> list[dict[str, Any]]:
    providers = (
        mail_config.get("providers")
        if isinstance(mail_config.get("providers"), list)
        else []
    )
    want = normalize_provider_type(str(provider_type or "").strip()) if provider_type else ""
    # short aliases from UI / CLI
    if want in {"outlook", "ms", "microsoft"}:
        want = "outlook_token"
    elif want in {"icloud", "apple", "hme", "hide_my_email"}:
        want = "icloud_api"
    elif want in {"fastmail", "mailcode"}:
        want = "fastmail_api"
    elif want in {"smsbower_email", "sms_bower_mail"}:
        want = "smsbower_mail"
    elif want in {"odm", "online_dispo", "onlinedispomail", "disposablemail"}:
        want = "online_disposablemail"
    elif want in {"auto", "any", "all", ""}:
        want = ""

    entries: list[dict[str, Any]] = []
    for i, item in enumerate(providers):
        if not isinstance(item, dict):
            continue
        if not item.get("enable", True):
            continue
        ptype = normalize_provider_type(str(item.get("type") or ""))
        if ptype not in CANONICAL_PROVIDER_TYPES:
            continue
        if want and ptype != want:
            continue
        entries.append(
            dict(item, type=ptype, provider_ref=f"{ptype}#{i + 1}")
        )
    return entries


def _build_provider(entry: dict, conf: dict):
    ptype = normalize_provider_type(str(entry.get("type") or ""))
    if ptype == "icloud_api":
        return ICloudApiProvider(entry, conf)
    if ptype == "outlook_token":
        return OutlookTokenProvider(entry, conf)
    if ptype == "maddy_webui":
        return MaddyWebuiProvider(entry, conf)
    if ptype == "fastmail_api":
        return FastmailApiProvider(entry, conf)
    if ptype == "smsbower_mail":
        return SmsBowerMailProvider(entry, conf)
    if ptype == "online_disposablemail":
        return OnlineDisposableMailProvider(entry, conf)
    raise RuntimeError(f"Unsupported mail provider type: {entry.get('type')}")


def _known_mailbox_bindings() -> dict[str, str]:
    """Collect addresses that already represent an account, including split slots."""
    # Include the source paths as well as their replacement-safe stamps.  The
    # path component matters for tests and for deployments that rotate data
    # directories while preserving an empty (0, 0, 0) stamp.
    try:
        from common.account_store import (
            ACCOUNTS_DB_FILE,
            ACCOUNTS_FILE,
            account_email_set,
            account_store_revision,
        )
    except Exception:
        ACCOUNTS_DB_FILE = Path("")  # type: ignore[assignment]
        ACCOUNTS_FILE = Path("")  # type: ignore[assignment]
        account_email_set = None  # type: ignore[assignment]
        account_store_revision = None  # type: ignore[assignment]
    try:
        revision = int(account_store_revision() if callable(account_store_revision) else 0)
    except Exception:
        revision = 0
    key = (
        str(ACCOUNT_TRASH_FILE),
        _mailbox_source_stamp(ACCOUNT_TRASH_FILE),
        str(CDKS_FILE),
        _mailbox_source_stamp(CDKS_FILE),
        revision,
        str(ACCOUNTS_FILE),
        _mailbox_source_stamp(ACCOUNTS_FILE),
        str(ACCOUNTS_DB_FILE),
        _mailbox_source_stamp(ACCOUNTS_DB_FILE),
        _mailbox_source_stamp(Path(f"{ACCOUNTS_DB_FILE}-wal")),
        id(account_email_set),
    )

    global _KNOWN_MAILBOX_BINDINGS_CACHE_KEY, _KNOWN_MAILBOX_BINDINGS_CACHE_VALUE
    with _KNOWN_MAILBOX_BINDINGS_CACHE_LOCK:
        cached = _KNOWN_MAILBOX_BINDINGS_CACHE_VALUE
        if cached is not None and _KNOWN_MAILBOX_BINDINGS_CACHE_KEY == key:
            return dict(cached)

        try:
            emails = account_email_set() if callable(account_email_set) else set()
        except Exception:
            emails = set()
        known: dict[str, str] = {
            str(email).strip().lower(): "registered_account"
            for email in emails
            if str(email).strip()
        }

        def add_records(path: Path, *, nested_record: bool, reason: str) -> None:
            try:
                payload = json.loads(path.read_text(encoding="utf-8"))
            except Exception:
                return
            if not isinstance(payload, list):
                return
            for row in payload:
                source = (
                    row.get("record")
                    if nested_record and isinstance(row, dict)
                    else row
                )
                if not isinstance(source, dict):
                    continue
                email = str(source.get("email") or "").strip().lower()
                if email:
                    known[email] = reason

        # panel_ops already parses the large trash file for the operations
        # page. Reuse its derived email index so a cold status/operations
        # request does not decode the same JSON twice.
        try:
            from common.panel_ops import trash_email_reasons

            known.update(trash_email_reasons(ACCOUNT_TRASH_FILE))
        except Exception:
            add_records(ACCOUNT_TRASH_FILE, nested_record=True, reason="known_deactivated")
        add_records(CDKS_FILE, nested_record=False, reason="cdk_bound")
        _KNOWN_MAILBOX_BINDINGS_CACHE_KEY = key
        _KNOWN_MAILBOX_BINDINGS_CACHE_VALUE = dict(known)
        return dict(known)


def reconcile_registered_mailbox_states(
    mail_config: dict,
    *,
    provider_type: str | None = None,
    _known: dict[str, str] | None = None,
) -> int:
    """Quarantine primary and split addresses already bound to an account or CDK."""
    known = _known if isinstance(_known, dict) else _known_mailbox_bindings()
    if not known:
        return 0

    configured: set[str] = set()
    for entry in _iter_provider_entries(mail_config, provider_type=provider_type):
        ptype = normalize_provider_type(str(entry.get("type") or ""))
        lines = str(entry.get("mailboxes") or entry.get("pool") or "")
        if ptype == "icloud_api":
            pool = parse_icloud_credentials(lines)
        elif ptype == "maddy_webui":
            pool = parse_domain_mailboxes(lines)
        elif ptype in {"smsbower_mail", "online_disposablemail"}:
            pool = []
        else:
            pool = parse_outlook_credentials(lines)
        configured.update(
            str(item.get("email") or "").strip().lower()
            for item in pool
            if str(item.get("email") or "").strip()
        )
    targets = {
        email
        for email in known
        if email in configured
        or (
            is_split_mailbox_address(email)
            and base_mailbox_address(email) in configured
        )
    }
    if not targets:
        return 0

    with _mailbox_state_lock:
        with _with_state_file_lock():
            store = _load_state_unlocked()
            changed = 0
            for email in targets:
                entry = store.get(email)
                current = str((entry or {}).get("state") or "").strip().lower()
                if current in {
                    "used", "token_invalid", "in_use", "cooldown"
                }:
                    continue
                store[email] = {
                    "state": "used",
                    "reason": known[email],
                    "updated_at": datetime.now(BJ_TZ).strftime(
                        "%Y-%m-%d %H:%M:%S%z"
                    ),
                }
                changed += 1
            if changed:
                _save_state_unlocked(store)
            return changed



def count_pool_capacity(
    mail_config: dict,
    *,
    provider_type: str | None = None,
    fixed_email: str | None = None,
    fixed_alias_count: int | None = None,
) -> dict[str, Any]:
    """Return primary and split-alias registration slots per mailbox.

    ``total`` remains the physical mailbox count. ``available`` and
    ``total_slots`` describe registration slots and include split aliases. A
    registered ``fixed_email`` gets the requested number of fresh aliases;
    normal pool capacity keeps the single-alias default.
    """
    entries = _iter_provider_entries(mail_config, provider_type=provider_type)
    known = _known_mailbox_bindings()
    reconcile_registered_mailbox_states(
        mail_config,
        provider_type=provider_type,
        _known=known,
    )
    requested = str(fixed_email or "").strip().lower()
    requested_base = base_mailbox_address(requested) if requested else ""
    requested_is_split = is_split_mailbox_address(requested) if requested else False
    requested_alias_count = max(
        1,
        int(fixed_alias_count or SPLIT_SLOTS_PER_MAILBOX),
    )
    store = _load_state()
    stats = {
        "total": 0,
        "total_slots": 0,
        "available": 0,
        "primary_available": 0,
        "used": 0,
        "failed": 0,
        "in_use": 0,
        "token_invalid": 0,
        "cooldown": 0,
        "split_total": 0,
        "split_available": 0,
        "split_slot_available": 0,
        "split_used": 0,
        "split_failed": 0,
        "split_in_use": 0,
        "split_token_invalid": 0,
        "split_cooldown": 0,
        "fixed_email_mode": "",
        "emails": [],
    }
    primary_emails: list[str] = []
    split_emails: list[str] = []
    bound_aliases: dict[str, set[str]] = {}
    for email in known:
        if is_split_mailbox_address(email):
            bound_aliases.setdefault(base_mailbox_address(email), set()).add(email)
    for email, state_entry in store.items():
        if (
            is_split_mailbox_address(email)
            and isinstance(state_entry, dict)
            and str(state_entry.get("state") or "").strip().lower() == "used"
        ):
            bound_aliases.setdefault(base_mailbox_address(email), set()).add(email)

    def state_category(entry: dict[str, Any] | None) -> str:
        state = str((entry or {}).get("state") or "").strip().lower()
        if state in {"cooldown", "in_use"} and _entry_available(entry):
            return "available"
        return state if state in UNAVAILABLE_STATES | {"in_use", "cooldown"} else "available"

    seen: set[str] = set()
    for entry in entries:
        ptype = normalize_provider_type(str(entry.get("type") or ""))
        lines = str(entry.get("mailboxes") or entry.get("pool") or "")
        if ptype == "icloud_api":
            pool = parse_icloud_credentials(lines)
        elif ptype == "maddy_webui":
            blocked_domains = _maddy_blocked_domains(entry)
            if requested:
                requested_domain = requested.rsplit("@", 1)[1] if "@" in requested else ""
                configured_domains = {
                    str(value or "").strip().lower()
                    for value in (
                        entry.get("default_domain"),
                        entry.get("domain"),
                    )
                    if str(value or "").strip()
                }
                configured_domains -= blocked_domains
                extra_domains = entry.get("domains")
                if isinstance(extra_domains, list):
                    configured_domains.update(
                        str(value or "").strip().lower()
                        for value in extra_domains
                        if str(value or "").strip()
                    )
                elif isinstance(extra_domains, str):
                    configured_domains.update(
                        value.strip().lower()
                        for value in re.split(r"[,;\s]+", extra_domains)
                        if value.strip()
                    )
                configured_domains -= blocked_domains
                if requested_domain and requested_domain in blocked_domains:
                    continue
                if (
                    configured_domains
                    and requested_domain
                    and requested_domain not in configured_domains
                ):
                    continue
                stats["total"] = int(stats["total"]) + 1
                stats["total_slots"] = int(stats["total_slots"]) + 1
                stats["fixed_email_mode"] = (
                    "exact_alias" if requested_is_split else "exact_primary"
                )
                entry_state = store.get(requested) if isinstance(store.get(requested), dict) else None
                category = state_category(entry_state)
                if category == "available":
                    stats["primary_available"] = int(stats["primary_available"]) + 1
                    primary_emails.append(requested)
                else:
                    stats[category] = int(stats.get(category) or 0) + 1
                continue
            try:
                dynamic_capacity = int(
                    entry.get("capacity")
                    or entry.get("auto_create_limit")
                    or MADDY_WEBUI_DEFAULT_CAPACITY
                )
            except (TypeError, ValueError):
                dynamic_capacity = MADDY_WEBUI_DEFAULT_CAPACITY
            dynamic_capacity = max(0, min(500, dynamic_capacity))
            stats["total"] = int(stats["total"]) + dynamic_capacity
            stats["total_slots"] = int(stats["total_slots"]) + dynamic_capacity
            stats["primary_available"] = int(stats["primary_available"]) + dynamic_capacity
            continue
        elif ptype == "fastmail_api":
            cached_rows = parse_domain_mailboxes(lines)
            if requested:
                # Claim the requested address only when this pool really owns
                # it: a cached alias row or a fastmail state entry.
                entry_state = (
                    store.get(requested) if isinstance(store.get(requested), dict) else None
                )
                owns = any(
                    item["email"].strip().lower() == requested for item in cached_rows
                ) or (
                    isinstance(entry_state, dict)
                    and normalize_provider_type(str(entry_state.get("provider") or ""))
                    == "fastmail_api"
                )
                if not owns:
                    continue
                stats["total"] = int(stats["total"]) + 1
                stats["total_slots"] = int(stats["total_slots"]) + 1
                stats["fixed_email_mode"] = (
                    "exact_alias" if requested_is_split else "exact_primary"
                )
                category = state_category(entry_state)
                if category == "available":
                    stats["primary_available"] = int(stats["primary_available"]) + 1
                    primary_emails.append(requested)
                else:
                    stats[category] = int(stats.get(category) or 0) + 1
                continue
            try:
                fallback_capacity = max(
                    0, min(615, int(entry.get("capacity") or FASTMAIL_API_DEFAULT_CAPACITY))
                )
            except (TypeError, ValueError):
                fallback_capacity = FASTMAIL_API_DEFAULT_CAPACITY
            conf = _make_config(mail_config)
            conf["request_timeout"] = min(float(conf.get("request_timeout") or 30), 6.0)
            fastmail_provider = FastmailApiProvider(entry, conf)
            try:
                summary = fastmail_provider.pool_summary()
            finally:
                fastmail_provider.close()
            if summary.get("error"):
                available = fallback_capacity
                total = fallback_capacity
            else:
                available = max(0, int(summary.get("available") or 0))
                total = max(available, int(summary.get("total") or 0))
            stats["total"] = int(stats["total"]) + total
            stats["total_slots"] = int(stats["total_slots"]) + total
            stats["primary_available"] = int(stats["primary_available"]) + available
            continue
        elif ptype == "smsbower_mail":
            # Activations are allocated dynamically and cannot satisfy a fixed
            # address request. getPriceRests is the authoritative live stock.
            if requested:
                continue
            try:
                fallback_capacity = max(0, int(entry.get("capacity") or 0))
            except (TypeError, ValueError):
                fallback_capacity = 0
            conf = _make_config(mail_config)
            conf["request_timeout"] = min(
                float(conf.get("request_timeout") or 30), 6.0
            )
            smsbower_provider = SmsBowerMailProvider(entry, conf)
            try:
                summary = smsbower_provider.availability_summary()
                dynamic_capacity = max(
                    0, int(summary.get("count") or 0)
                )
            except Exception as error:
                logger.warning(
                    "[smsbower_mail] getPriceRests failed; using configured "
                    "capacity=%d: %s",
                    fallback_capacity,
                    smsbower_provider._safe_detail(error)[:200],
                )
                dynamic_capacity = fallback_capacity
            finally:
                smsbower_provider.close()
            stats["total"] = int(stats["total"]) + dynamic_capacity
            slots_per_mailbox = 2 if smsbower_provider.register_child else 1
            stats["total_slots"] = int(stats["total_slots"]) + dynamic_capacity * slots_per_mailbox
            stats["primary_available"] = (
                int(stats["primary_available"]) + dynamic_capacity
            )
            if smsbower_provider.register_child:
                stats["split_available"] = int(stats["split_available"]) + dynamic_capacity
                stats["split_total"] = int(stats["split_total"]) + dynamic_capacity
            continue
        elif ptype == "online_disposablemail":
            # Orders are bought on demand and cannot satisfy a fixed address
            # request. Sales availability and balance gate configured capacity.
            if requested:
                continue
            try:
                configured_capacity = max(0, int(entry.get("capacity") or 0))
            except (TypeError, ValueError):
                configured_capacity = 0
            conf = _make_config(mail_config)
            conf["request_timeout"] = min(
                float(conf.get("request_timeout") or 30), 6.0
            )
            conf["capacity"] = configured_capacity
            odm_provider = OnlineDisposableMailProvider(entry, conf)
            try:
                summary = odm_provider.availability_summary()
                dynamic_capacity = max(
                    0, int(summary.get("capacity") or 0)
                )
            except Exception as error:
                logger.warning(
                    "[online_disposablemail] availability check failed; "
                    "scheduling capacity=0: %s",
                    odm_provider._safe_detail(error)[:200],
                )
                dynamic_capacity = 0
            finally:
                odm_provider.close()
            stats["total"] = int(stats["total"]) + dynamic_capacity
            stats["total_slots"] = int(stats["total_slots"]) + dynamic_capacity
            stats["primary_available"] = (
                int(stats["primary_available"]) + dynamic_capacity
            )
            continue
        else:
            pool = parse_outlook_credentials(lines)
        for item in pool:
            email = item["email"].strip().lower()
            if not email or email in seen:
                continue
            base = base_mailbox_address(email)
            if requested and base != requested_base:
                continue
            seen.add(email)
            stats["total"] = int(stats["total"]) + 1
            base_entry = store.get(email) if isinstance(store.get(email), dict) else None
            base_category = state_category(base_entry)

            registered_primary = email in known or base_category == "used"
            fixed_base_alias_mode = bool(
                requested and not requested_is_split and registered_primary
            )
            if fixed_base_alias_mode:
                stats["fixed_email_mode"] = "alias_batch"
            elif requested_is_split:
                stats["fixed_email_mode"] = "exact_alias"
            elif requested:
                stats["fixed_email_mode"] = "exact_primary"

            include_primary = not requested or (
                not requested_is_split and not fixed_base_alias_mode
            )
            if include_primary:
                stats["total_slots"] = int(stats["total_slots"]) + 1
                if base_category == "available":
                    stats["primary_available"] = int(stats["primary_available"]) + 1
                    primary_emails.append(email)
                else:
                    stats[base_category] = int(stats.get(base_category) or 0) + 1

            if requested and not requested_is_split and not fixed_base_alias_mode:
                continue

            if requested_is_split:
                alias_candidates = [requested]
                logical_alias_total = 1
                already_bound: set[str] = set()
            else:
                already_bound = bound_aliases.get(base, set())
                if fixed_base_alias_mode:
                    # Hard one-split-per-mailbox policy: a primary mailbox may
                    # spend at most SPLIT_SLOTS_PER_MAILBOX alias slots in
                    # total. A mailbox whose slot is already bound never yields
                    # fresh aliases; fixed batches must not mint second slots
                    # past historical registrations.
                    wanted_aliases = max(
                        0,
                        min(
                            requested_alias_count,
                            SPLIT_SLOTS_PER_MAILBOX
                            - min(SPLIT_SLOTS_PER_MAILBOX, len(already_bound)),
                        ),
                    )
                    alias_candidates = []
                    projected_available = 0
                    slot = 1
                    scan_limit = SPLIT_SLOTS_PER_MAILBOX
                    while (
                        projected_available < wanted_aliases
                        and slot <= scan_limit
                    ):
                        alias = split_mailbox_address(base, slot)
                        slot += 1
                        if alias in already_bound:
                            continue
                        alias_candidates.append(alias)
                        alias_entry = (
                            store.get(alias)
                            if isinstance(store.get(alias), dict)
                            else None
                        )
                        alias_category = state_category(alias_entry)
                        if alias_entry is None and base_category in {
                            "failed", "token_invalid", "in_use", "cooldown"
                        }:
                            alias_category = base_category
                        if alias_category == "available":
                            projected_available += 1
                    logical_alias_total = len(already_bound) + len(alias_candidates)
                else:
                    logical_alias_total = SPLIT_SLOTS_PER_MAILBOX
                    remaining_slots = max(
                        0,
                        logical_alias_total
                        - min(logical_alias_total, len(already_bound)),
                    )
                    alias_candidates = [
                        alias
                        for alias in split_mailbox_addresses(base)
                        if alias not in already_bound
                    ][:remaining_slots]

            stats["total_slots"] = int(stats["total_slots"]) + logical_alias_total
            stats["split_total"] = int(stats["split_total"]) + logical_alias_total
            stats["split_used"] = int(stats["split_used"]) + min(
                logical_alias_total,
                len(already_bound),
            )

            for split_address in alias_candidates:
                split_entry = (
                    store.get(split_address)
                    if isinstance(store.get(split_address), dict)
                    else None
                )
                split_category = state_category(split_entry)
                if split_entry is None and base_category in {
                    "failed", "token_invalid", "in_use", "cooldown"
                }:
                    split_category = base_category
                if split_category == "available":
                    stats["split_available"] = int(stats["split_available"]) + 1
                    split_emails.append(split_address)
                elif split_category == "used":
                    stats["split_used"] = int(stats["split_used"]) + 1
                else:
                    key = f"split_{split_category}"
                    stats[key] = int(stats.get(key) or 0) + 1

    stats["available"] = (
        int(stats["primary_available"]) + int(stats["split_available"])
    )
    if not requested and split_emails:
        grouped_aliases: dict[str, list[str]] = {}
        for alias in split_emails:
            grouped_aliases.setdefault(base_mailbox_address(alias), []).append(alias)
        # Keep alias slots grouped by base for deterministic scheduling. With the
        # current single-alias policy this is mostly a stable ordering guard.
        paired = [items for items in grouped_aliases.values() if len(items) >= 2]
        singles = [items for items in grouped_aliases.values() if len(items) < 2]
        split_emails = [alias for items in (*paired, *singles) for alias in items]
    # Slot capacity is independent from the current mailbox credential health.
    # The scheduler continues to use split_available/available (usable now),
    # while the dashboard can show the configured slot capacity.
    stats["split_slot_available"] = max(
        0,
        int(stats["split_total"]) - int(stats["split_used"]),
    )
    stats["emails"] = [*primary_emails, *split_emails]
    return stats


def create_mailbox(
    mail_config: dict,
    username: str | None = None,
    *,
    provider_type: str | None = None,
    allow_used: bool = False,
) -> dict:
    """Allocate one mailbox from configured providers.

    provider_type:
      - None / "auto" → all enabled providers
      - "outlook" / "outlook_token"
      - "icloud" / "icloud_api"
      - "maddy" / "maddy_webui"
      - "fastmail" / "fastmail_api"
      - "smsbower_mail" / "smsbower_email"
      - "online_disposablemail" / "odm"
    """
    entries = _iter_provider_entries(mail_config, provider_type=provider_type)
    if not entries:
        want = str(provider_type or "auto").strip() or "auto"
        raise RuntimeError(
            f"No mail provider found for type={want!r}. "
            f"Enable outlook_token, icloud_api, maddy_webui, "
            f"fastmail_api, smsbower_mail, or online_disposablemail "
            f"under mail.providers"
        )

    conf = _make_config(mail_config)
    requested = str(username or "").strip().lower()
    if not requested:
        reconcile_registered_mailbox_states(
            mail_config,
            provider_type=provider_type,
        )
    last_error = ""

    # If a specific email is requested, isolate the provider that owns it.
    # An iCloud alias cannot be fulfilled by an unrelated Outlook credential;
    # preserving this boundary keeps the reported exhaustion reason accurate.
    ordered = list(entries)
    if requested:
        matched = []
        others = []
        for entry in entries:
            ptype = normalize_provider_type(str(entry.get("type") or ""))
            if ptype == "outlook_token":
                pool = parse_outlook_credentials(
                    str(entry.get("mailboxes") or entry.get("pool") or "")
                )
            elif ptype == "icloud_api":
                pool = parse_icloud_credentials(
                    str(entry.get("mailboxes") or entry.get("pool") or "")
                )
            else:
                pool = [{"email": requested}]
            if any(
                base_mailbox_address(item["email"].strip().lower())
                == base_mailbox_address(requested)
                for item in pool
            ):
                matched.append(entry)
            else:
                others.append(entry)
        ordered = matched if matched else others

    for entry in ordered:
        try:
            provider = _build_provider(entry, conf)
        except Exception as error:
            # 配置类型错误（如 message_limit 非数字）不应中断整个 provider 轮换
            last_error = f"build provider failed: {error}"
            continue
        try:
            mailbox = provider.create_mailbox(username, allow_used=allow_used)
            mark_mailbox_code_boundary(mailbox, grace_seconds=0)
            return mailbox
        except RuntimeError as error:
            if (
                isinstance(error, (SmsBowerMailError, OnlineDisposableMailError))
                and error.business_error == "already_registered"
            ):
                raise
            if (
                isinstance(error, SmsBowerMailError)
                and error.activation_outcome_uncertain
            ):
                raise
            last_error = str(error)
            continue
        except Exception as error:
            # 网络层等非 RuntimeError 异常同样换下一个 provider，
            # 避免单个 provider 内部状态（已写 in_use）外泄成未释放预约
            if (
                isinstance(error, (SmsBowerMailError, OnlineDisposableMailError))
                and error.business_error == "already_registered"
            ):
                raise
            if (
                isinstance(error, SmsBowerMailError)
                and error.activation_outcome_uncertain
            ):
                raise
            last_error = str(error)
            continue
        finally:
            provider.close()
    raise RuntimeError(last_error or "All mail providers exhausted")


def wait_for_code(mail_config: dict, mailbox: dict, stop_check=None) -> str | None:
    entries = _iter_provider_entries(mail_config, provider_type=None)
    # Also include disabled providers so wait still works if mailbox was already created
    raw_providers = (
        mail_config.get("providers")
        if isinstance(mail_config.get("providers"), list)
        else []
    )
    for i, item in enumerate(raw_providers):
        if not isinstance(item, dict):
            continue
        ptype = normalize_provider_type(str(item.get("type") or ""))
        if ptype not in CANONICAL_PROVIDER_TYPES:
            continue
        ref = f"{ptype}#{i + 1}"
        if not any(e.get("provider_ref") == ref for e in entries):
            entries.append(dict(item, type=ptype, provider_ref=ref))

    provider_ref = str(mailbox.get("provider_ref") or "")
    provider_type = normalize_provider_type(str(mailbox.get("provider") or ""))

    entry = next(
        (item for item in entries if item.get("provider_ref") == provider_ref),
        None,
    )
    if entry is None and provider_type:
        entry = next(
            (
                item
                for item in entries
                if normalize_provider_type(str(item.get("type") or "")) == provider_type
            ),
            None,
        )
    if entry is None:
        # mailbox 有明确 provider 归属；匹配不到说明配置已删除该 provider，
        # 静默换成第一个 provider 会用错误的池白等到超时
        raise RuntimeError(
            f"Mailbox provider missing from config (ref={provider_ref}, "
            f"type={provider_type})"
        )

    conf = _make_config(mail_config)
    provider = _build_provider(entry, conf)
    try:
        return provider.wait_for_code(mailbox, stop_check=stop_check)
    finally:
        provider.close()


