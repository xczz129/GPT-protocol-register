        "cloudflare",
        "navigation timeout",
        "timeout",
        "socket hang up",
        "connection reset",
        "connection closed",
        "connection refused",
        "max retries",
        "failed to establish",
        "httpconnectionpool",
        "newconnectionerror",
        "api 不可用",
        "api 不可达",
        "未启动",
        "create browser",
        "open browser",
        "registration_disallowed",
        "验证码获取超时",
        "等待注册验证码超时",
        "登录验证码超时",
        "创建账号失败",
        "浏览器进程已断开",
        "create browser failed",
        "open browser failed",
        "aadsts70000",
        "scopes requested are unauthorized",
        "cancelled",
        "stop requested",
        "icloud api request failed",
        "icloud sync_error",
        "fastmail api transient http",
        "fastmail code api request failed",
        "curl: (35)",
        "tls connect error",
        "proxyerror",
        "pool exhausted",  # previous task left in_use — free and retry
        "in_use=",
        "email_submit_stuck",
        "stuck_on_login",
        "stuck_on_password",
        "passwordless_switch_failed",
        "stuck_on_verification",
        "onboarding_failed",
        "async_generator",
        "not iterable",
        "goto_failed",
        "cf_blocked",
        "no_email_input",
        "no_session_cookie",
        "no_access_token",
        "stale_signup_otp_session",
        "auth_undefined",
        "auth_unknown",
        "auth_oauthcallback",
