SPLIT_SLOTS_PER_MAILBOX = 1


def split_mailbox_address(email: str, slot: int = 1) -> str:
    """Return a stable plus-address for one of a mailbox's alias slots."""
    base = base_mailbox_address(str(email or "").strip().lower())
    if "@" not in base:
        return base
    local, domain = base.rsplit("@", 1)
    slot_number = max(1, int(slot or 1))
    # Slot 1 preserves the address generated by earlier releases. Additional
    # slots use a distinct deterministic seed, so restarts never change them.
    seed = base if slot_number == 1 else f"{base}#split-slot-{slot_number}"
    tag = hashlib.sha256(seed.encode("utf-8")).hexdigest()[:12]
    return f"{local}+split{tag}@{domain}"


def split_mailbox_addresses(
    email: str,
    count: int = SPLIT_SLOTS_PER_MAILBOX,
) -> list[str]:
    return [
        split_mailbox_address(email, slot)
        for slot in range(1, max(0, int(count or 0)) + 1)
    ]


def is_split_mailbox_address(email: str) -> bool:
    address = str(email or "").strip().lower()
    return bool(address and "+" in address.rsplit("@", 1)[0])


def _requested_mailbox_slot(requested: str, credential_email: str) -> str:
    credential = str(credential_email or "").strip().lower()
    wanted = str(requested or "").strip().lower()
    if not wanted:
        return credential
    return wanted if base_mailbox_address(wanted) == base_mailbox_address(credential) else ""


def _normalize_domain_values(raw: Any) -> list[str]:
    values: list[str] = []
    if isinstance(raw, list):
        values = [str(item or "").strip().lower() for item in raw]
    elif isinstance(raw, str):
        values = [
            item.strip().lower()
            for item in re.split(r"[,;\s]+", raw)
            if item.strip()
        ]
    seen: set[str] = set()
    out: list[str] = []
    for value in values:
        if value and value not in seen:
            seen.add(value)
            out.append(value)
    return out


