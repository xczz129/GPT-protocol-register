    def _read_graph(self, access_token: str) -> list[dict[str, Any]]:
        resp = self.session.get(
            OUTLOOK_GRAPH_MESSAGES_URL,
            headers={
                "Authorization": f"Bearer {access_token}",
                "Accept": "application/json",
                "User-Agent": self.conf["user_agent"],
            },
            params={
                "$top": self.message_limit,
                "$orderby": "receivedDateTime desc",
                "$select": "subject,receivedDateTime,from,toRecipients,ccRecipients,bccRecipients,body,bodyPreview",
            },
            timeout=self.conf["request_timeout"],
        )
        try:
            data = resp.json()
        except Exception:
            data = {}
        if resp.status_code != 200:
            detail = (
                data.get("error", {}).get("message")
                if isinstance(data.get("error"), dict)
                else resp.text[:300]
            )
            raise RuntimeError(f"OutlookToken Graph failed: HTTP {resp.status_code}, {detail}")
        items = data.get("value") if isinstance(data, dict) else None
        return [item for item in items if isinstance(item, dict)] if isinstance(items, list) else []

    @staticmethod
    def _graph_sender(message: dict[str, Any]) -> str:
        sender = message.get("from") or {}
        if isinstance(sender, dict):
            address = sender.get("emailAddress") or {}
            if isinstance(address, dict):
                return str(address.get("address") or address.get("name") or "")
        return ""

    @staticmethod
    def _graph_recipients(message: dict[str, Any]) -> list[str]:
        recipients: list[str] = []
        for key in ("toRecipients", "ccRecipients", "bccRecipients"):
            values = message.get(key)
            if not isinstance(values, list):
                continue
            for item in values:
                if not isinstance(item, dict):
                    continue
                address = item.get("emailAddress") if isinstance(item.get("emailAddress"), dict) else {}
                value = str(address.get("address") or "").strip().lower()
                if value:
                    recipients.append(value)
        return recipients

    def _normalize_graph_item(self, mailbox: dict[str, Any], item: dict[str, Any]) -> dict[str, Any]:
        body = item.get("body") if isinstance(item.get("body"), dict) else {}
        content_type = str(body.get("contentType") or "").lower()
        content = str(body.get("content") or "")
        text_content = content if content_type != "html" else str(item.get("bodyPreview") or "")
        html_content = content if content_type == "html" else ""
        return {
            "provider": self.name,
            "mailbox": mailbox["address"],
            "message_id": str(item.get("id") or ""),
            "subject": str(item.get("subject") or ""),
            "sender": self._graph_sender(item),
            "recipients": self._graph_recipients(item),
            "text_content": text_content,
            "html_content": html_content,
            "received_at": _parse_received_at(item.get("receivedDateTime")),
        }

    def _graph_messages(self, mailbox: dict[str, Any], access_token: str) -> list[dict[str, Any]]:
        return [self._normalize_graph_item(mailbox, item) for item in self._read_graph(access_token)]

    def _imap_messages(self, mailbox: dict[str, Any], access_token: str) -> list[dict[str, Any]]:
        login_address = str(
            mailbox.get("login_address") or mailbox.get("base_address") or mailbox["address"]
        )
        auth_string = f"user={login_address}\x01auth=Bearer {access_token}\x01\x01"
        imap = imaplib.IMAP4_SSL(self.imap_host, timeout=self.conf["request_timeout"])
        try:
            imap.authenticate("XOAUTH2", lambda _: auth_string.encode("utf-8"))
            status, _ = imap.select("INBOX", readonly=True)
            if status != "OK":
                raise RuntimeError("OutlookToken IMAP select INBOX failed")
            status, data = imap.uid("search", None, "ALL")
            if status != "OK" or not data or not data[0]:
                return []
            uids = data[0].split()[-self.message_limit :]
            uid_set = ",".join(uid.decode("ascii") for uid in uids)
            status, fetched = imap.uid("fetch", uid_set, "(RFC822)")
            if status != "OK":
                return []
            raw_payloads = [
                part[1]
                for part in fetched
                if isinstance(part, tuple) and isinstance(part[1], bytes)
            ]
            return [
                self._parse_imap_message(mailbox, raw_payload)
                for raw_payload in reversed(raw_payloads)
            ]
        finally:
            try:
                imap.logout()
            except Exception:
                pass

    def _parse_imap_message(self, mailbox: dict[str, Any], raw: bytes) -> dict[str, Any]:
        message = message_from_bytes(raw, policy=policy.default)
        try:
            received = _parse_received_at(parsedate_to_datetime(str(message.get("Date") or "")))
        except Exception:
            received = None
        plain: list[str] = []
        html: list[str] = []
        for part in message.walk() if message.is_multipart() else [message]:
            if part.get_content_maintype() == "multipart":
                continue
            try:
                payload = part.get_content()
            except Exception:
                continue
            if not payload:
                continue
            if part.get_content_type() == "text/html":
                html.append(str(payload))
            else:
                plain.append(str(payload))

        def _decode(value: str | None) -> str:
            if not value:
                return ""
            try:
                return str(make_header(decode_header(value)))
            except Exception:
                return value

        recipients = []
        for header in ("To", "Cc", "Delivered-To", "X-Original-To"):
            value = _decode(str(message.get(header) or ""))
            recipients.extend(
                addr.lower()
                for addr in re.findall(
                    r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}", value
                )
            )

        return {
            "provider": self.name,
            "mailbox": mailbox["address"],
            "message_id": _decode(str(message.get("Message-ID") or "")),
            "subject": _decode(str(message.get("Subject") or "")),
            "sender": _decode(str(message.get("From") or "")),
            "recipients": recipients,
            "text_content": "\n".join(plain).strip(),
            "html_content": "\n".join(html).strip(),
            "received_at": received,
        }

    def fetch_recent_messages(self, mailbox: dict[str, Any]) -> list[dict[str, Any]]:
        client_id = str(mailbox.get("client_id") or "").strip()
        refresh_token = str(mailbox.get("refresh_token") or "").strip()
        if not client_id or not refresh_token:
            raise RuntimeError("OutlookToken mailbox missing client_id or refresh_token")
        errors: list[str] = []
        try_graph = self.mode in {"graph", "auto"}
        try_imap = self.mode in {"imap", "auto", "graph"}
        if try_graph:
            try:
                access_token = self._cached_access_token(
                    mailbox, client_id, refresh_token, OUTLOOK_GRAPH_SCOPE
                )
                return self._graph_messages(mailbox, access_token)
            except Exception as error:
                errors.append(f"graph: {error}")
                if self.mode == "graph":
                    logger.warning(
                        "[%s] Graph 失败，改用 IMAP: %s",
                        self.name,
                        str(error)[:200],
                    )
        if try_imap:
            try:
                access_token = self._cached_access_token(
                    mailbox, client_id, refresh_token, OUTLOOK_IMAP_SCOPE
                )
                return self._imap_messages(mailbox, access_token)
            except Exception as error:
                errors.append(f"imap: {error}")
                if self.mode == "imap":
                    raise
        if errors:
            raise RuntimeError("; ".join(errors))
        return []

    def wait_for_code(
        self,
        mailbox: dict[str, Any],
        stop_check=None,
    ) -> str | None:
        seen_value = mailbox.setdefault("_seen_code_message_refs", [])
        if not isinstance(seen_value, list):
            seen_value = []
            mailbox["_seen_code_message_refs"] = seen_value
        seen_refs = {str(item) for item in seen_value}

        deadline = time.monotonic() + self.conf["wait_timeout"]
        attempt = 0
        while time.monotonic() < deadline:
            if callable(stop_check) and stop_check():
                logger.info("[%s] 已停止，中止等待验证码 %s", self.name, mailbox.get("address", "?"))
                return None
            attempt += 1
            try:
                messages = self.fetch_recent_messages(mailbox)
            except Exception as error:
                logger.warning(
                    "[%s] 轮询验证码 #%d 失败 %s: %s",
                    self.name,
                    attempt,
                    mailbox.get("address", "?"),
                    error,
                )
                for _ in range(max(1, int(max(0.2, self.conf["wait_interval"]) * 5))):
                    if callable(stop_check) and stop_check():
                        return None
                    time.sleep(0.2)
                continue
            target_address = str(mailbox.get("address") or "").strip().lower()
            for message in messages:
                if _message_before_code_boundary(mailbox, message):
                    continue
                recipients = [
                    str(r or "").strip().lower() for r in (message.get("recipients") or [])
                ]
                if target_address and recipients and target_address not in recipients:
                    continue
                ref = _message_tracking_ref(message)
                if ref in seen_refs:
                    continue
                code = _extract_code(message)
                if code:
                    seen_value.append(ref)
                    return code
                seen_refs.add(ref)
            for _ in range(max(1, int(max(0.2, self.conf["wait_interval"]) * 5))):
                if callable(stop_check) and stop_check():
                    return None
                time.sleep(0.2)
        return None


