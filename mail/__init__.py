def _smsbower_settlement_age_seconds(entry: dict[str, Any]) -> float:
    raw = str(
        entry.get("smsbower_settlement_started_at")
        or entry.get("smsbower_settlement_updated_at")
        or entry.get("updated_at")
        or ""
    ).strip()
    if not raw:
        return 0.0
    try:
        recorded = datetime.fromisoformat(raw)
        if recorded.tzinfo is None:
            recorded = recorded.replace(tzinfo=timezone.utc)
        return max(
            0.0,
            (datetime.now(timezone.utc) - recorded.astimezone(timezone.utc)).total_seconds(),
        )
    except Exception:
        return 0.0


def _icloud_message_for_code(raw: Any) -> dict[str, Any]:
    """Normalize the iCloud API's mail preview variants for local OTP parsing."""
    if not isinstance(raw, dict):
        return {}
    body = raw.get("body") if isinstance(raw.get("body"), dict) else {}

    def first_value(*keys: str) -> str:
        for key in keys:
            value = raw.get(key)
            if value not in (None, ""):
                return str(value)
            value = body.get(key)
            if value not in (None, ""):
                return str(value)
        return ""

    return {
        "subject": first_value("subject", "title"),
        "text_content": first_value(
            "text_content", "text", "body_text", "content", "preview"
        ),
        "html_content": first_value("html_content", "html", "body_html"),
        "received_at": _parse_received_at(
            raw.get("received_at") or raw.get("date") or raw.get("timestamp")
        ),
    }


def _icloud_payload_messages(data: dict[str, Any]) -> list[dict[str, Any]]:
    messages: list[dict[str, Any]] = []
    seen_ids: set[str] = set()
    for key in ("mail", "message", "email", "latest"):
        value = data.get(key)
        values = value if isinstance(value, list) else [value]
        for item in values:
            if not isinstance(item, dict):
                continue
            item_id = str(item.get("id") or item.get("message_id") or "")
            if item_id and item_id in seen_ids:
                continue
            if item_id:
                seen_ids.add(item_id)
            messages.append(item)
    values = data.get("messages")
    if isinstance(values, list):
        for item in values:
            if not isinstance(item, dict):
                continue
            item_id = str(item.get("id") or item.get("message_id") or "")
            if item_id and item_id in seen_ids:
                continue
            if item_id:
                seen_ids.add(item_id)
            messages.append(item)
    if not messages and any(
        key in data for key in ("subject", "text", "preview", "body", "html")
    ):
        messages.append(data)
    return messages


def _icloud_payload_code_candidates(
    data: dict[str, Any],
) -> list[tuple[str, str, datetime | None]]:
    """Return top-level and nested OTP candidates from one API response."""
    candidates: list[tuple[str, str, datetime | None]] = []
    seen: set[tuple[str, str, str]] = set()

    def add(code: Any, subject: Any = "", received_at: Any = None) -> None:
        value = str(code or "").strip()
        title = str(subject or "").strip()
        received = _parse_received_at(received_at)
        received_key = received.isoformat() if received else ""
        if not value or (value, title, received_key) in seen:
            return
        seen.add((value, title, received_key))
        candidates.append((value, title, received))

    first_message = _icloud_payload_messages(data)
    first_subject = first_message[0].get("subject") if first_message else ""
    add(data.get("code"), first_subject, data.get("received_at"))
    for raw in first_message:
        add(
            raw.get("code") or raw.get("otp") or raw.get("verification_code"),
            raw.get("subject"),
            raw.get("received_at") or raw.get("date") or raw.get("timestamp"),
        )
        parsed = _icloud_message_for_code(raw)
        add(_extract_code(parsed), parsed.get("subject"), parsed.get("received_at"))
    return candidates


class OutlookTokenProvider:
    name = "outlook_token"

    def __init__(self, entry: dict, conf: dict):
        self.conf = conf
        self.provider_ref = str(entry.get("provider_ref") or "")
        self.label = str(entry.get("label") or self.provider_ref or "Outlook Pool")
        self.pool = parse_outlook_credentials(
            str(entry.get("mailboxes") or entry.get("pool") or "")
        )
        self.mode = str(entry.get("mode") or "imap").strip().lower() or "imap"
        if self.mode not in {"graph", "imap", "auto"}:
            self.mode = "imap"
        self.imap_host = (
            str(entry.get("imap_host") or OUTLOOK_DEFAULT_IMAP_HOST).strip()
            or OUTLOOK_DEFAULT_IMAP_HOST
        )
        self.message_limit = max(1, int(entry.get("message_limit") or 10))
        self.session = _http_session()

    def close(self) -> None:
        self.session.close()

    def _exchange_refresh_token(self, client_id: str, refresh_token: str, scope: str) -> str:
        last_err = None
        for attempt in range(3):
            try:
                resp = self.session.post(
                    OUTLOOK_TOKEN_URL,
                    data={
                        "client_id": client_id,
                        "grant_type": "refresh_token",
                        "refresh_token": refresh_token,
                        "scope": scope,
                    },
                    headers={
                        "Content-Type": "application/x-www-form-urlencoded",
                        "User-Agent": self.conf["user_agent"],
                    },
                    timeout=self.conf["request_timeout"],
                )
                try:
                    data = resp.json()
                except Exception:
                    data = {}
                if resp.status_code != 200:
                    detail = (
                        data.get("error_description")
                        or data.get("error")
                        or resp.text[:300]
                    )
                    err_text = str(detail)
                    if "AADSTS70000" in err_text or "scopes requested are unauthorized" in err_text:
                        if "Mail.Read" in scope or "graph.microsoft.com" in scope:
                            err_text = (
                                f"{err_text} | hint: this token has no Graph Mail.Read; "
                                f"set mail.providers[].mode=imap (or auto)"
                            )
                    raise OutlookTokenError(
                        f"OutlookToken refresh failed: HTTP {resp.status_code}, {err_text}"
                    )
                access_token = str(data.get("access_token") or "").strip()
                if not access_token:
                    raise OutlookTokenError("OutlookToken refresh response missing access_token")
                return access_token
            except OutlookTokenError:
                raise
            except Exception as e:
                last_err = e
                if attempt < 2:
                    time.sleep(1.5)
                    continue
        raise OutlookTokenError(f"token exchange failed: {last_err}")

    def _cached_access_token(
        self, mailbox: dict[str, Any], client_id: str, refresh_token: str, scope: str
    ) -> str:
        cache = mailbox.get("_outlook_token_cache")
        if not isinstance(cache, dict):
            cache = {}
            mailbox["_outlook_token_cache"] = cache
        cached = cache.get(scope)
        if isinstance(cached, tuple) and len(cached) == 2 and time.monotonic() < cached[1]:
            return str(cached[0])
        token = self._exchange_refresh_token(client_id, refresh_token, scope)
        cache[scope] = (token, time.monotonic() + 600)
        return token

    def _verify_imap_access(
        self, email: str, client_id: str, refresh_token: str
    ) -> tuple[bool, str]:
        try:
            access_token = self._exchange_refresh_token(
                client_id, refresh_token, OUTLOOK_IMAP_SCOPE
            )
        except OutlookTokenError as error:
            return False, f"token_invalid: {error}"
        except Exception as error:
            return False, f"token_exchange: {error}"

        auth_string = f"user={email}\x01auth=Bearer {access_token}\x01\x01"
        try:
            imap = imaplib.IMAP4_SSL(self.imap_host, timeout=self.conf["request_timeout"])
            try:
                imap.authenticate("XOAUTH2", lambda _: auth_string.encode("utf-8"))
                status, _ = imap.select("INBOX", readonly=True)
                if status != "OK":
                    return False, "imap_select_failed"
                return True, ""
            finally:
                try:
                    imap.logout()
                except Exception:
                    logger.debug("_verify_imap_access: ignoring exception", exc_info=True)
        except Exception as error:
            return False, str(error)

    def create_mailbox(
        self,
        username: str | None = None,
        *,
        allow_used: bool = False,
    ) -> dict[str, Any]:
        if not self.pool:
            raise RuntimeError(
                "OutlookToken pool is empty. "
                "Import email----password----client_id----refresh_token lines."
            )
        requested_email = str(username or "").strip().lower()
        tried: set[str] = set()
        while True:
            with _mailbox_state_lock:
                with _with_state_file_lock():
                    store = _load_state_unlocked()

                    def candidate_available(item: dict[str, str]) -> bool:
                        credential_email = item["email"].strip().lower()
                        slot = _requested_mailbox_slot(requested_email, credential_email)
                        if not slot or credential_email in tried:
                            return False
                        entry = store.get(slot)
                        return _entry_available(entry) or (
                            allow_used
                            and str((entry or {}).get("state") or "").lower() == "used"
                        )

                    credential = next(
                        (
                            item
                            for item in self.pool
                            if candidate_available(item)
                        ),
                        None,
                    )
                    if credential is None:
                        scope = f" for {requested_email}" if requested_email else ""
                        reasons: dict[str, int] = {}
                        for item in self.pool:
                            credential_email = item["email"].strip().lower()
                            slot = _requested_mailbox_slot(requested_email, credential_email)
                            st = store.get(slot or credential_email) or {}
                            key = str(st.get("state") or "available")
                            reasons[key] = reasons.get(key, 0) + 1
                        detail = ", ".join(f"{k}={v}" for k, v in sorted(reasons.items()))
                        raise RuntimeError(
                            f"[{self.label}] OutlookToken pool exhausted{scope} "
                            f"({len(self.pool)} total, tried {len(tried)}; {detail or 'none'}). "
                            f"在面板点「释放 failed/in_use」或清空 data/outlook_token_state.json 后重试。"
                        )
                    email_lower = credential["email"].strip().lower()
                    slot_address = _requested_mailbox_slot(requested_email, email_lower)
                    prev_entry = store.get(slot_address) if isinstance(store.get(slot_address), dict) else {}
                    store[slot_address] = {
                        "state": "in_use",
                        "reason": "",
                        # 记录预约前状态：释放时恢复 used 等终态，避免重复注册
                        "_prev_state": str(prev_entry.get("state") or ""),
                        "updated_at": datetime.now(BJ_TZ).strftime("%Y-%m-%d %H:%M:%S%z"),
                    }
                    _save_state_unlocked(store)

            tried.add(email_lower)
            login_email = base_mailbox_address(credential["email"])
            if self.mode == "graph":
                return {
                    "provider": self.name,
                    "provider_ref": self.provider_ref,
                    "address": slot_address,
                    "login_address": login_email,
                    "base_address": login_email,
                    "label": self.label,
                    "password": credential.get("password", ""),
                    "client_id": credential["client_id"],
                    "refresh_token": credential["refresh_token"],
                }

            ok, reason = self._verify_imap_access(
                login_email,
                credential["client_id"],
                credential["refresh_token"],
            )
            if ok or self.mode == "auto":
                if not ok and self.mode == "auto":
                    logger.warning(
                        "[%s] IMAP check failed for %s: %s",
                        self.name,
                        credential["email"],
                        reason,
                    )
                return {
                    "provider": self.name,
                    "provider_ref": self.provider_ref,
                    "address": slot_address,
                    "login_address": login_email,
                    "base_address": login_email,
                    "label": self.label,
                    "password": credential.get("password", ""),
                    "client_id": credential["client_id"],
                    "refresh_token": credential["refresh_token"],
                }

            state = "token_invalid" if "token_invalid" in reason else "failed"
            # 预约写入的是 slot_address（可能是 split 别名槽），释放/标记也必须
            # 作用于同一 key，否则 slot 永远 in_use 锁 15 分钟、基础邮箱被误标
            if slot_address and slot_address != email_lower:
                _set_state(slot_address, state, reason[:300])
            else:
                _set_state(credential["email"], state, reason[:300])
            logger.warning("[%s] skipping %s: %s", self.name, credential["email"], reason)

    def _read_graph(self, access_token: str) -> list[dict[str, Any]]:
        resp = self.session.get(
            OUTLOOK_GRAPH_MESSAGES_URL,
            headers={
                "Authorization": f"Bearer {access_token}",
                "Accept": "application/json",
                "User-Agent": self.conf["user_agent"],
            },
            params={
                "$top": self.message_limit,
                "$orderby": "receivedDateTime desc",
                "$select": "subject,receivedDateTime,from,toRecipients,ccRecipients,bccRecipients,body,bodyPreview",
            },
            timeout=self.conf["request_timeout"],
        )
        try:
            data = resp.json()
        except Exception:
            data = {}
        if resp.status_code != 200:
            detail = (
                data.get("error", {}).get("message")
                if isinstance(data.get("error"), dict)
                else resp.text[:300]
            )
            raise RuntimeError(f"OutlookToken Graph failed: HTTP {resp.status_code}, {detail}")
        items = data.get("value") if isinstance(data, dict) else None
        return [item for item in items if isinstance(item, dict)] if isinstance(items, list) else []

    @staticmethod
    def _graph_sender(message: dict[str, Any]) -> str:
        sender = message.get("from") or {}
        if isinstance(sender, dict):
            address = sender.get("emailAddress") or {}
            if isinstance(address, dict):
                return str(address.get("address") or address.get("name") or "")
        return ""

    @staticmethod
    def _graph_recipients(message: dict[str, Any]) -> list[str]:
        recipients: list[str] = []
        for key in ("toRecipients", "ccRecipients", "bccRecipients"):
            values = message.get(key)
            if not isinstance(values, list):
                continue
            for item in values:
                if not isinstance(item, dict):
                    continue
                address = item.get("emailAddress") if isinstance(item.get("emailAddress"), dict) else {}
                value = str(address.get("address") or "").strip().lower()
                if value:
                    recipients.append(value)
        return recipients

    def _normalize_graph_item(self, mailbox: dict[str, Any], item: dict[str, Any]) -> dict[str, Any]:
        body = item.get("body") if isinstance(item.get("body"), dict) else {}
        content_type = str(body.get("contentType") or "").lower()
        content = str(body.get("content") or "")
        text_content = content if content_type != "html" else str(item.get("bodyPreview") or "")
        html_content = content if content_type == "html" else ""
        return {
            "provider": self.name,
            "mailbox": mailbox["address"],
            "message_id": str(item.get("id") or ""),
            "subject": str(item.get("subject") or ""),
            "sender": self._graph_sender(item),
            "recipients": self._graph_recipients(item),
            "text_content": text_content,
            "html_content": html_content,
            "received_at": _parse_received_at(item.get("receivedDateTime")),
        }

    def _graph_messages(self, mailbox: dict[str, Any], access_token: str) -> list[dict[str, Any]]:
        return [self._normalize_graph_item(mailbox, item) for item in self._read_graph(access_token)]

    def _imap_messages(self, mailbox: dict[str, Any], access_token: str) -> list[dict[str, Any]]:
        login_address = str(
            mailbox.get("login_address") or mailbox.get("base_address") or mailbox["address"]
        )
        auth_string = f"user={login_address}\x01auth=Bearer {access_token}\x01\x01"
        imap = imaplib.IMAP4_SSL(self.imap_host, timeout=self.conf["request_timeout"])
        try:
            imap.authenticate("XOAUTH2", lambda _: auth_string.encode("utf-8"))
            status, _ = imap.select("INBOX", readonly=True)
            if status != "OK":
                raise RuntimeError("OutlookToken IMAP select INBOX failed")
            status, data = imap.uid("search", None, "ALL")
            if status != "OK" or not data or not data[0]:
                return []
            uids = data[0].split()[-self.message_limit :]
            uid_set = ",".join(uid.decode("ascii") for uid in uids)
            status, fetched = imap.uid("fetch", uid_set, "(RFC822)")
            if status != "OK":
                return []
            raw_payloads = [
                part[1]
                for part in fetched
                if isinstance(part, tuple) and isinstance(part[1], bytes)
            ]
            return [
                self._parse_imap_message(mailbox, raw_payload)
                for raw_payload in reversed(raw_payloads)
            ]
        finally:
            try:
                imap.logout()
            except Exception:
                logger.debug("_imap_messages: ignoring exception", exc_info=True)

    def _parse_imap_message(self, mailbox: dict[str, Any], raw: bytes) -> dict[str, Any]:
        message = message_from_bytes(raw, policy=policy.default)
        try:
            received = _parse_received_at(parsedate_to_datetime(str(message.get("Date") or "")))
        except Exception:
            received = None
        plain: list[str] = []
        html: list[str] = []
        for part in message.walk() if message.is_multipart() else [message]:
            if part.get_content_maintype() == "multipart":
                continue
            try:
                payload = part.get_content()
            except Exception:
                continue
            if not payload:
                continue
            if part.get_content_type() == "text/html":
                html.append(str(payload))
            else:
                plain.append(str(payload))

        def _decode(value: str | None) -> str:
            if not value:
                return ""
            try:
                return str(make_header(decode_header(value)))
            except Exception:
                return value

        recipients = []
        for header in ("To", "Cc", "Delivered-To", "X-Original-To"):
            value = _decode(str(message.get(header) or ""))
            recipients.extend(
                addr.lower()
                for addr in re.findall(
                    r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}", value
                )
            )

        return {
            "provider": self.name,
            "mailbox": mailbox["address"],
            "message_id": _decode(str(message.get("Message-ID") or "")),
            "subject": _decode(str(message.get("Subject") or "")),
            "sender": _decode(str(message.get("From") or "")),
            "recipients": recipients,
            "text_content": "\n".join(plain).strip(),
            "html_content": "\n".join(html).strip(),
            "received_at": received,
        }

    def fetch_recent_messages(self, mailbox: dict[str, Any]) -> list[dict[str, Any]]:
        client_id = str(mailbox.get("client_id") or "").strip()
        refresh_token = str(mailbox.get("refresh_token") or "").strip()
        if not client_id or not refresh_token:
            raise RuntimeError("OutlookToken mailbox missing client_id or refresh_token")
        errors: list[str] = []
        try_graph = self.mode in {"graph", "auto"}
        try_imap = self.mode in {"imap", "auto", "graph"}
        if try_graph:
            try:
                access_token = self._cached_access_token(
                    mailbox, client_id, refresh_token, OUTLOOK_GRAPH_SCOPE
                )
                return self._graph_messages(mailbox, access_token)
            except Exception as error:
                errors.append(f"graph: {_redact_secrets(error)}")
                if self.mode == "graph":
                    logger.warning(
                        "[%s] Graph 失败，改用 IMAP: %s",
                        self.name,
                        _redact_secrets(str(error)[:200]),
                    )
        if try_imap:
            try:
                access_token = self._cached_access_token(
                    mailbox, client_id, refresh_token, OUTLOOK_IMAP_SCOPE
                )
                return self._imap_messages(mailbox, access_token)
            except Exception as error:
                errors.append(f"imap: {_redact_secrets(error)}")
                if self.mode == "imap":
                    raise
        if errors:
            raise RuntimeError("; ".join(errors))
        return []

    def wait_for_code(
        self,
        mailbox: dict[str, Any],
        stop_check=None,
    ) -> str | None:
        seen_value = mailbox.setdefault("_seen_code_message_refs", [])
        if not isinstance(seen_value, list):
            seen_value = []
            mailbox["_seen_code_message_refs"] = seen_value
        seen_refs = {str(item) for item in seen_value}

        deadline = time.monotonic() + self.conf["wait_timeout"]
        attempt = 0
        while time.monotonic() < deadline:
            if callable(stop_check) and stop_check():
                logger.info("[%s] 已停止，中止等待验证码 %s", self.name, mailbox.get("address", "?"))
                return None
            attempt += 1
            try:
                messages = self.fetch_recent_messages(mailbox)
            except Exception as error:
                logger.warning(
                    "[%s] 轮询验证码 #%d 失败 %s: %s",
                    self.name,
                    attempt,
                    mailbox.get("address", "?"),
                    error,
                )
                for _ in range(max(1, int(max(0.2, self.conf["wait_interval"]) * 5))):
                    if callable(stop_check) and stop_check():
                        return None
                    time.sleep(0.2)
                continue
            target_address = str(mailbox.get("address") or "").strip().lower()
            for message in messages:
                if _message_before_code_boundary(mailbox, message):
                    continue
                recipients = [
                    str(r or "").strip().lower() for r in (message.get("recipients") or [])
                ]
                if target_address and recipients and target_address not in recipients:
                    continue
                ref = _message_tracking_ref(message)
                if ref in seen_refs:
                    continue
                code = _extract_code(message)
                if code:
                    seen_value.append(ref)
                    return code
                seen_refs.add(ref)
            for _ in range(max(1, int(max(0.2, self.conf["wait_interval"]) * 5))):
                if callable(stop_check) and stop_check():
                    return None
                time.sleep(0.2)
        return None


