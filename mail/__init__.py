def _parse_state_payload(data: Any) -> dict[str, dict[str, Any]]:
    state: dict[str, dict[str, Any]] = {}
    if not isinstance(data, dict):
        return state
    for key, value in data.items():
        email = str(key).strip().lower()
        if not email:
            continue
        if isinstance(value, dict):
            entry = {
                "state": str(value.get("state") or "used").strip() or "used",
                "reason": str(value.get("reason") or ""),
                "updated_at": str(value.get("updated_at") or ""),
            }
            # Preserve provider metadata (provider/provider_ref/label/api_base/
            # account/key/...) so dynamic pools keep their attribution across
            # read-modify-write cycles from other providers and processes.
            for meta_key, meta_value in value.items():
                if meta_key not in entry:
                    entry[meta_key] = meta_value
            state[email] = entry
        else:
            state[email] = {"state": str(value or "used"), "reason": "", "updated_at": ""}
    return state


def _load_state_unlocked() -> dict[str, dict[str, Any]]:
    try:
        if not STATE_FILE.exists():
            return {}
        data = json.loads(STATE_FILE.read_text(encoding="utf-8"))
    except Exception as error:
        # JSON 损坏时先把坏文件隔离存档再返回空：直接当空状态继续写会
        # 让全部 used/failed 历史丢失，已注册邮箱重新回池造成重复注册
        try:
            stamp = time.strftime("%Y%m%d-%H%M%S")
            STATE_FILE.rename(
                STATE_FILE.with_name(f"{STATE_FILE.name}.corrupt-{stamp}")
            )
            logger.error(
                "mailbox state file corrupt, archived and reset: %s (%s)",
                STATE_FILE, error,
            )
        except Exception:
            logger.exception("failed to archive corrupt mailbox state file")
        return {}
    return _parse_state_payload(data)


def _save_state_unlocked(state: dict[str, dict[str, Any]]) -> None:
    import os
    import tempfile

    STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    ordered = {key: state[key] for key in sorted(state)}
    payload = json.dumps(ordered, ensure_ascii=False, indent=2) + "\n"
    fd, tmp_name = tempfile.mkstemp(
        prefix=f".{STATE_FILE.name}.",
        suffix=".tmp",
        dir=str(STATE_FILE.parent),
        text=True,
    )
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())
        Path(tmp_name).replace(STATE_FILE)
        try:
            os.chmod(STATE_FILE, 0o600)
        except Exception:
            logger.debug("_save_state_unlocked: ignoring exception", exc_info=True)
    finally:
        try:
            Path(tmp_name).unlink(missing_ok=True)
        except Exception:
            logger.debug("_save_state_unlocked: ignoring exception", exc_info=True)


def _with_state_file_lock():
    """Cross-process exclusive lock for mailbox state JSON."""
    from contextlib import contextmanager

    @contextmanager
    def _cm():
        STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
        lock_path = STATE_FILE.with_suffix(STATE_FILE.suffix + ".lock")
        with lock_path.open("a+", encoding="utf-8") as lock_file:
            if fcntl is not None:
                fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX)
            try:
                yield
            finally:
                if fcntl is not None:
                    fcntl.flock(lock_file.fileno(), fcntl.LOCK_UN)

    return _cm()


def _load_state() -> dict[str, dict[str, Any]]:
    with _mailbox_state_lock:
        with _with_state_file_lock():
            return _load_state_unlocked()


def _save_state(state: dict[str, dict[str, Any]]) -> None:
    with _mailbox_state_lock:
        with _with_state_file_lock():
            _save_state_unlocked(state)


def _entry_available(entry: dict[str, Any] | None) -> bool:
    if not isinstance(entry, dict):
        return True
    current = str(entry.get("state") or "")
    if current == "cooldown":
        updated_at = str(entry.get("updated_at") or "")
        try:
            ts = datetime.fromisoformat(updated_at)
            age = (
                datetime.now(timezone.utc)
                - (ts if ts.tzinfo else ts.replace(tzinfo=timezone.utc))
            ).total_seconds()
            return age >= RATE_LIMIT_COOLDOWN_SECONDS
        except Exception:
            return False
    if current in UNAVAILABLE_STATES:
        return False
    if current == "in_use":
        updated_at = str(entry.get("updated_at") or "")
        try:
            ts = datetime.fromisoformat(updated_at)
            age = (
                datetime.now(timezone.utc)
                - (ts if ts.tzinfo else ts.replace(tzinfo=timezone.utc))
            ).total_seconds()
            return age >= IN_USE_STALE_SECONDS
        except Exception:
            return True
    return True


def _has_pending_smsbower_settlement(entry: dict[str, Any] | None) -> bool:
    if not isinstance(entry, dict):
        return False
    return bool(
        entry.get("smsbower_activation_outcome_unknown")
        or entry.get("smsbower_pending_status") in {2, 3, "2", "3"}
    )


def _set_state(address: str, state: str, reason: str = "") -> None:
    target = str(address or "").strip().lower()
    if not target:
        return
    with _mailbox_state_lock:
        with _with_state_file_lock():
            store = _load_state_unlocked()
            previous = store.get(target) if isinstance(store.get(target), dict) else {}
            metadata = {
                key: value
                for key, value in previous.items()
                if key not in {"state", "reason", "updated_at", "_prev_state"}
            }
            store[target] = {
                **metadata,
                "state": str(state),
                "reason": str(reason or ""),
                "updated_at": datetime.now(BJ_TZ).strftime("%Y-%m-%d %H:%M:%S%z"),
            }
            _save_state_unlocked(store)


def _release_state(address: str, *, any_state: bool = False) -> None:
    """Drop mailbox state so it becomes available again.

    By default only clears ``in_use``. Pass any_state=True to also clear
    failed/token_invalid (used for browser or network infrastructure errors).
    """
    target = str(address or "").strip().lower()
    if not target:
        return
    with _mailbox_state_lock:
        with _with_state_file_lock():
            store = _load_state_unlocked()
            entry = store.get(target)
            if not isinstance(entry, dict):
                return
            if _has_pending_smsbower_settlement(entry):
                return
            st = str(entry.get("state") or "")
            if st == "in_use":
                # 预约前是 used（allow_used 复用）的邮箱，释放时恢复 used 而不是
                # 直接变回 available，否则会被当作全新邮箱重复注册
                prev = str(entry.get("_prev_state") or "")
                if prev in UNAVAILABLE_STATES:
                    entry.pop("_prev_state", None)
                    entry["state"] = prev
                    entry["reason"] = (
                        "restored after transient failure; original state kept"
                    )
                    _save_state_unlocked(store)
                else:
                    store.pop(target, None)
                    _save_state_unlocked(store)
            elif any_state:
                store.pop(target, None)
                _save_state_unlocked(store)


def _message_tracking_ref(message: dict[str, Any]) -> str:
    provider = str(message.get("provider") or "").strip()
    mailbox = str(message.get("mailbox") or "").strip()
    message_id = str(message.get("message_id") or "").strip()
    if message_id:
        return f"id:{provider}:{mailbox}:{message_id}"
    received_at = message.get("received_at")
    received_value = (
        received_at.isoformat()
        if isinstance(received_at, datetime)
        else str(received_at or "")
    )
    content = "\n".join(
        str(message.get(key) or "")
        for key in ("subject", "sender", "text_content", "html_content")
    )
    digest = hashlib.sha256(content.encode("utf-8", errors="replace")).hexdigest()
    return f"content:{provider}:{mailbox}:{received_value}:{digest}"


def _message_before_code_boundary(mailbox: dict[str, Any], message: dict[str, Any]) -> bool:
    boundary = _mailbox_code_boundary(mailbox)
    received_at = message.get("received_at")
    if not isinstance(boundary, datetime) or not isinstance(received_at, datetime):
        return False
    if not received_at.tzinfo:
        received_at = received_at.replace(tzinfo=timezone.utc)
    return received_at < boundary


def _parse_received_at(value: Any) -> datetime | None:
    if isinstance(value, (int, float)):
        try:
            return datetime.fromtimestamp(float(value), tz=timezone.utc)
        except Exception:
            return None
    text = str(value or "").strip()
    if not text:
        return None
    try:
        date = datetime.fromisoformat(text[:-1] + "+00:00" if text.endswith("Z") else text)
        return date if date.tzinfo else date.replace(tzinfo=timezone.utc)
    except Exception:
        logger.debug("_parse_received_at: ignoring exception", exc_info=True)
    try:
        date = parsedate_to_datetime(text)
        return date if date.tzinfo else date.replace(tzinfo=timezone.utc)
    except Exception:
        return None


def _mailbox_code_boundary(mailbox: dict[str, Any]) -> datetime | None:
    """Return the newest boundary written by either registration flow."""
    boundaries: list[datetime] = []
    for value in (
        mailbox.get("_code_not_before"),
        mailbox.get("_received_after"),
    ):
        if isinstance(value, datetime):
            boundary = value
        else:
            boundary = _parse_received_at(value)
        if boundary is None:
            continue
        if not boundary.tzinfo:
            boundary = boundary.replace(tzinfo=timezone.utc)
        boundaries.append(boundary)
    return max(boundaries) if boundaries else None


def mark_mailbox_code_boundary(
    mailbox: dict[str, Any],
    *,
    grace_seconds: float = OTP_CODE_GRACE_SECONDS,
    reset_seen_codes: bool = False,
) -> datetime:
    """Mark the start of a new OTP transaction for every mail provider."""
    try:
        grace = max(0.0, float(grace_seconds))
    except (TypeError, ValueError):
        grace = OTP_CODE_GRACE_SECONDS
    boundary = datetime.now(timezone.utc) - timedelta(seconds=grace)
    mailbox["_code_not_before"] = boundary
    mailbox["_received_after"] = boundary.isoformat()
    if reset_seen_codes:
        seen_codes = mailbox.get("_seen_otp_codes")
        if isinstance(seen_codes, list):
            seen_codes.clear()
    return boundary


