    def _request_code(
        self,
        mailbox: dict[str, Any],
        *,
        timeout: int,
        exclude: list[str],
    ) -> dict[str, Any]:
        api_key = str(mailbox.get("api_key") or "").strip()
        email = str(mailbox.get("address") or "").strip()
        if not api_key:
            raise ICloudApiError("iCloud mailbox missing api_key")
        base = str(mailbox.get("api_base") or self.api_base).rstrip("/")
        api_timeout = max(
            1,
            min(ICLOUD_WAIT_REQUEST_MAX_SECONDS, int(timeout)),
        )
        now = time.monotonic()
        try:
            last_sync = float(mailbox.get("_icloud_wait_last_sync_monotonic") or 0)
        except (TypeError, ValueError):
            last_sync = 0.0
        try:
            resync_interval = float(
                self.conf.get("icloud_resync_interval")
                or ICLOUD_RESYNC_INTERVAL_SECONDS
            )
        except (TypeError, ValueError):
            resync_interval = ICLOUD_RESYNC_INTERVAL_SECONDS
        resync_interval = max(5.0, min(60.0, resync_interval))
        should_sync = last_sync <= 0 or now - last_sync >= resync_interval
        params: dict[str, Any] = {
            "key": api_key,
            "timeout": api_timeout,
            "interval": max(2, min(15, int(self.conf.get("wait_interval") or 3))),
            "sync": 1 if should_sync else 0,
            "max_age_seconds": ICLOUD_WAIT_MAX_AGE_SECONDS,
        }
        if email:
            params["email"] = email
        if exclude:
            params["exclude"] = ",".join(exclude)
        after = self._after_epoch(mailbox)
        if after is not None:
            params["after"] = after

        if should_sync:
            mailbox["_icloud_wait_last_sync_monotonic"] = now
        url = f"{base}/api/v1/code/wait"
        # A Cloudflare 504 is the gateway timing out while the mailbox API is
        # still polling. Retry the same poll briefly, then let wait_for_code
        # fall back to /messages without quarantining the mailbox.
        http_timeout = max(
            float(self.conf["request_timeout"]),
            float(api_timeout) + 15.0,
        )
        resp = None
        last_error: Exception | None = None
        for request_attempt in range(ICLOUD_WAIT_HTTP_RETRIES):
            try:
                resp = self.session.get(
                    url,
                    params=params,
                    headers={
                        "Accept": "application/json",
                        "User-Agent": self.conf["user_agent"],
                    },
                    timeout=http_timeout,
                )
                status = int(getattr(resp, "status_code", 0) or 0)
                if status not in ICLOUD_TRANSIENT_HTTP_STATUSES:
                    break
                if request_attempt + 1 < ICLOUD_WAIT_HTTP_RETRIES:
                    # Do not repeat another full long poll after the gateway
                    # already timed out. A short second poll reaches the cache
                    # quickly and keeps the registration deadline bounded.
                    params["timeout"] = min(15, api_timeout)
                    http_timeout = max(
                        float(self.conf["request_timeout"]),
                        float(params["timeout"]) + 15.0,
                    )
                    time.sleep(0.75 * (request_attempt + 1))
            except Exception as error:
                last_error = error
                if request_attempt + 1 >= ICLOUD_WAIT_HTTP_RETRIES:
                    raise ICloudApiError(
                        f"iCloud wait API request failed: {error}"
                    ) from error
                params["timeout"] = min(15, api_timeout)
                http_timeout = max(
                    float(self.conf["request_timeout"]),
                    float(params["timeout"]) + 15.0,
                )
                time.sleep(0.75 * (request_attempt + 1))
        if resp is None:
            raise ICloudApiError(
                f"iCloud wait API request failed: {last_error or 'empty response'}"
            )

        try:
            data = resp.json()
        except Exception:
            data = {}
        if not isinstance(data, dict):
            data = {}

        if resp.status_code != 200:
            detail = data.get("error") or data.get("message") or resp.text[:300]
            raise ICloudApiError(f"iCloud API HTTP {resp.status_code}: {detail}")

        # Some backends return 200 with ok=false for config errors
        if data.get("ok") is False:
            detail = data.get("error") or data.get("sync_error") or "unknown error"
            raise ICloudApiError(f"iCloud API error: {detail}")

        # sync_error with empty code — treat as soft failure for this poll
        sync_error = str(data.get("sync_error") or "").strip()
        code = str(data.get("code") or "").strip()
        if sync_error and not code and not _icloud_payload_code_candidates(data):
            # e.g. server missing App-specific password — surface clearly
            raise ICloudApiError(f"iCloud sync_error: {sync_error}")

        return data

